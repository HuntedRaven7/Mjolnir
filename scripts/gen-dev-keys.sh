#!/usr/bin/env bash
# Generate THROWAWAY Secure Boot keys for local development / VM testing.
# NEVER use these on real hardware. Production keys come from CI secrets.
# Based on projectbluefin/server's scripts/gen-dev-keys.sh.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
KEYDIR="${1:-$ROOT/files/boot-keys}"
mkdir -p "$KEYDIR"
cd "$KEYDIR"

gen() {
  local name="$1" cn="$2"
  openssl req -new -x509 -newkey rsa:2048 -nodes -keyout "$name.key" \
    -out "$name.crt" -days 3650 -subj "/CN=$cn" >/dev/null 2>&1
  echo "generated $name.key / $name.crt"
}

gen PK "Mjolnir Dev PK"
gen KEK "Mjolnir Dev KEK"
gen DB "Mjolnir Dev DB"
cp DB.key VENDOR.key
cp DB.crt VENDOR.crt
chmod 0600 *.key
cat > README.md <<'EOF'
# Secure Boot keys (GITIGNORED)

These are throwaway development keys generated by `scripts/gen-dev-keys.sh`.
They are NOT for production. Production DB/PK/KEK keys are supplied by CI
secrets; never commit private keys to this repository.

Elements that consume these keys are signing-only and must never be added to
`base/os-stack.bst` or any runtime stack (their BST artifacts contain the keys).
EOF
echo "Dev keys written to $KEYDIR (gitignored)"
